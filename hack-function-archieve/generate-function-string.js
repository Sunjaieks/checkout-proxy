const fs = require('fs/promises');
const path = require('path');
const babelParser = require('@babel/parser');
const traverse = require('@babel/traverse').default;
const generator = require('@babel/generator').default;
const terser = require('terser');

async function processFile(filePath) {
    try {
        const originalCode = await fs.readFile(filePath, 'utf-8');

        const generatedBlockRegex = /\n*\s*\/\/ ----- Generated By Tool -----[\s\S]*/;

        const cleanCode = originalCode.replace(generatedBlockRegex, '').trimEnd();

        // to AST
        const ast = babelParser.parse(originalCode, {
            sourceType: 'module', // support import/export
        });

        const functionsMap = {};
        const processingPromises = [];

        console.log('processing...');

        // traverse AST and find all function declarations and expressions
         traverse(ast, {
            // find: function add() { ... }
             FunctionDeclaration(path) {
                const functionName = path.node.id.name;
                 processingPromises.push(processNode(functionName, path.node, functionsMap));
            },
            // find: const multiply = function() { ... } or const fetch = async () => { ... }
             VariableDeclarator(path) {
                if (
                    path.node.init &&
                    (path.node.init.type === 'FunctionExpression' ||
                        path.node.init.type === 'ArrowFunctionExpression')
                ) {
                    const functionName = path.node.id.name;
                    processingPromises.push(processNode(functionName, path.node.init, functionsMap));
                }
            },
        });

        await Promise.all(processingPromises);
        console.log(`found ${Object.keys(functionsMap).length} functions.`);

        const functionsObjectString = JSON.stringify(functionsMap, null, 2);

        const newGeneratedBlock = `\n\n// ----- Generated By Tool -----\nconst stringifiedFunctions = ${functionsObjectString};\n`;
        const finalCode = cleanCode + newGeneratedBlock;
        await fs.writeFile(filePath, finalCode, 'utf-8');

        console.log(`succeed!`);

    } catch (error) {
        console.error('error:', error);
    }
}

async function processNode(name, node, map) {
    if (!name || !node) return;

    // 1. generate function from AST node
    const { code: functionCode } = generator(node, { comments: false });

    // 2. use Terser to compress
    //    mangle: false keep variable names and function names
    //    compress: false avoid code transformation, only minify
    const result = await terser.minify(functionCode, {
        mangle: false,
        compress: false,
        output: {
            comments: false,
            semicolons: false,
            quote_style: 3
        },
    });

    if (result.code) {
        map[name] = node.type === 'ArrowFunctionExpression'
            ? `(${result.code.replace(/;$/, '')})`
            : result.code;
    }
}

processFile(path.resolve('./useful-hack-functions.js'));
